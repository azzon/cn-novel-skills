#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""multi_lens_coldread.py 多视角冷读调度器(问题2+3: 全过≠高质量)

五个独立视角,每个用不同的"人设"冷读同一章:
  1. 追更读者(爽不爽): 只关心"想不想看下一章"
  2. 弃书审判官(哪里无聊): 专找"我会在这里关掉页面"的段落
  3. 逻辑审查员(穿帮没): 专查前后矛盾/逻辑漏洞/角色行为不合理
  4. 文笔鉴赏家(AI感): 逐段判断"这像人写的还是像AI生成的"
  5. 目标受众(代入感): 用读者画像人设冷读"我是不是就是主角"

用法: python3 tools/multi_lens_coldread.py <章文件>
输出: 五视角报告(每视角独立打分+最致命问题)
"""
