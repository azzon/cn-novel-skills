def main():
    if len(sys.argv) < 2:
        print(__doc__); return 2
    fp = pathlib.Path(sys.argv[1]).resolve()
    if not fp.exists():
        print(f"文件不存在: {fp}"); return 2
    book = fp.parent.parent.parent  # text/卷N/file → 书根

    ch_match = re.search(r'第(\d+)章', fp.stem)
    ch = ch_match.group(1) if ch_match else "XXX"

    out_dir = book / "audit"
    out_dir.mkdir(exist_ok=True)

    print(f"═══ 多视角冷读: 第{ch}章 ═══")
    print(f"生成{len(LENSES)}个agent prompt → {out_dir}/mlcr-{ch}-lens<N>.md\n")

    for lens in LENSES:
        out = out_dir / f"mlcr-{ch}-lens{lens['id']}.md"
        prompt_text = lens["prompt"].replace("{body_path}", str(fp))
        out.write_text(prompt_text, encoding="utf-8")
        print(f"  ✅ lens{lens['id']}: {lens['name']} → {out.name}")

    print(f"\n── 派发指令 ──")
    print(f"逐个用Agent工具执行(每个独立派发,不共享上下文):")
    for lens in LENSES:
        print(f"  Agent(subagent_type=general-purpose, prompt=读{out_dir}/mlcr-{ch}-lens{lens['id']}.md并执行)")
    print(f"\n── 汇总规则 ──")
    print(f"  五视角均值≥7.0 = 通过")
    print(f"  任一视角≤5.0 = 打回(即使其他视角满分)")
    print(f"  '弃书审判官'高风险 = 直接打回")
    print(f"  '文笔鉴赏家'AI风险高 = 必须去AI化修订")
    return 0

if __name__ == "__main__":
    sys.exit(main())
