def main():
    if len(sys.argv) < 2:
        print(__doc__); return 2
    fp = pathlib.Path(sys.argv[1])
    if not fp.exists():
        print(f"文件不存在: {fp}"); return 2

    print(f"═══ 多视角冷读: {fp.name} ═══\n")
    print("本工具是调度器——实际冷读由5个独立AI代理执行。")
    print("每个代理只读本章文件,不知道其他代理的评分。\n")

    for i, lens in enumerate(LENSES, 1):
        print(f"── 透镜{i}: {lens['name']} ──")
        print(f"  人设: {lens['persona'][:60]}...")
        print(f"  评分: {lens['scoring']}")
        print(f"  焦点: {lens['focus']}")
        print(f"  调度: 派发独立代理,只读 {fp}")
        print()

    print("── 汇总规则 ──")
    print("  五视角均值≥7.0 = 通过")
    print("  任一视角≤5.0 = 打回(即使其他视角满分)")
    print("  '弃书审判官'发现高风险 = 直接打回")
    print("  '文笔鉴赏家'AI风险高 = 必须去AI化修订")
    print()
    print("── 与单视角冷读的区别 ──")
    print("  单视角(现行reader-proxy): AI评AI=确认偏差,倾向给面子分")
    print("  多视角: 5个不同人设=5把不同的尺子,'过得去'和'好看'分开量")
    return 0

if __name__ == "__main__":
    sys.exit(main())
